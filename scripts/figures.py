W_DTW = 4  # course window, samples (2 hours at 30-minute sampling)
HEADER = "<!-- generated by scripts/figures.py, do not edit -->"
WIDTH = 360  # viewBox width of every figure: one user unit is about 0.87 CSS px at 375 px (313 px wide)
HOURS = [(0, "00:00"), (12, "12:00"), (24, "24:00")]


# --- SVG helpers -------------------------------------------------------------------------

def f(v):
    """A coordinate with one decimal, without a trailing .0 (stable bytes)."""
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def esc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def document(height, title, desc, body):
    lines = [HEADER,
             f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {f(height)}" role="img">',
             f"<title>{esc(title)}</title>",
             f"<desc>{esc(desc)}</desc>",
             *body,
             "</svg>"]
    return "\n".join(lines) + "\n"


def text(x, y, s, cls="t-sm t-mono"):
    return f'<text class="{cls}" x="{f(x)}" y="{f(y)}">{esc(s)}</text>'


def line(x1, y1, x2, y2, cls="ln-soft", extra=""):
    return f'<line class="{cls}" x1="{f(x1)}" y1="{f(y1)}" x2="{f(x2)}" y2="{f(y2)}"{extra}/>'


def polyline(points, cls, extra=""):
    pts = " ".join(f"{f(x)},{f(y)}" for x, y in points)
    return f'<polyline class="{cls}" points="{pts}"{extra}/>'


def time_x(i, x0, w):
    """x of sample i: samples are half hours, the axis runs from 00:00 to 24:00."""
    return x0 + w * (i * 0.5) / 24.0


def series_points(y, x0, w, top, h, lo, hi):
    return [(time_x(i, x0, w), top + h - h * (v - lo) / (hi - lo)) for i, v in enumerate(y)]


def hour_hints(x0, w, y):
    """The short time axis: 00:00 at the left, 12:00 in the middle, 24:00 at the right."""
    anchors = {0: "t-sm t-mono", 12: "t-sm t-mono mid", 24: "t-sm t-mono end"}
    return [text(x0 + w * h / 24.0, y, label, anchors[h]) for h, label in HOURS]


