"""Generate the pilot figures (content/figures/*.svg) and numbers (content/figures/numbers.json).

Every drawn or quoted number comes from the tsc package on the frozen fixture
(fixtures/demand-12.csv). The SVG uses only the figure classes of site/theme.css,
so the theme decides every colour. Colours keep one meaning: series A (mon) or the
first group in ink, series B (sat) or the second group in accent, soft links and
frames in the line colour. Output is deterministic: same bytes on every run.

Run: uv run python scripts/figures.py
"""

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "code" / "python"))

from tsc.distances import dtw, dtw_path, euclidean, sbd, znorm  # noqa: E402
from tsc.group import average_linkage, distance_matrix, load_demand  # noqa: E402
from tsc.validity import check_dissimilarity, silhouette_from_matrix  # noqa: E402

OUT = ROOT / "content" / "figures"
W_DTW = 4  # course window, samples (2 hours at 30-minute sampling)
HEADER = "<!-- generated by scripts/figures.py, do not edit -->"
WIDTH = 360  # viewBox width of every figure: one user unit is about one CSS px at 375 px
HOURS = [(0, "00:00"), (12, "12:00"), (24, "24:00")]


# --- SVG helpers -------------------------------------------------------------------------

def f(v):
    """A coordinate with one decimal, without a trailing .0 (stable bytes)."""
    s = f"{v:.1f}"
    return s[:-2] if s.endswith(".0") else s


def esc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def document(height, title, desc, body):
    lines = [HEADER,
             f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {f(height)}" role="img">',
             f"<title>{esc(title)}</title>",
             f"<desc>{esc(desc)}</desc>",
             *body,
             "</svg>"]
    return "\n".join(lines) + "\n"


def text(x, y, s, cls="t-sm t-mono"):
    return f'<text class="{cls}" x="{f(x)}" y="{f(y)}">{esc(s)}</text>'


def line(x1, y1, x2, y2, cls="ln-soft", extra=""):
    return f'<line class="{cls}" x1="{f(x1)}" y1="{f(y1)}" x2="{f(x2)}" y2="{f(y2)}"{extra}/>'


def polyline(points, cls, extra=""):
    pts = " ".join(f"{f(x)},{f(y)}" for x, y in points)
    return f'<polyline class="{cls}" points="{pts}"{extra}/>'


def time_x(i, x0, w):
    """x of sample i: samples are half hours, the axis runs from 00:00 to 24:00."""
    return x0 + w * (i * 0.5) / 24.0


def series_points(y, x0, w, top, h, lo, hi):
    return [(time_x(i, x0, w), top + h - h * (v - lo) / (hi - lo)) for i, v in enumerate(y)]


def hour_hints(x0, w, y):
    """The short time axis: 00:00 at the left, 12:00 in the middle, 24:00 at the right."""
    anchors = {0: "t-sm t-mono", 12: "t-sm t-mono mid", 24: "t-sm t-mono end"}
    return [text(x0 + w * h / 24.0, y, label, anchors[h]) for h, label in HOURS]


# --- data --------------------------------------------------------------------------------

def load():
    ids, X, _ = load_demand()
    lo, hi = 0.0, float(np.ceil(X.max() * 10) / 10)  # one shared scale from 0 kW
    return ids, X, lo, hi


def question_labels(X):
    """Question A: raw Euclidean. Question B: z-normalisation plus SBD. Both average linkage, k = 2."""
    labels_a = average_linkage(distance_matrix(X, euclidean), 2)
    Z = np.array([znorm(x) for x in X])
    labels_b = average_linkage(distance_matrix(Z, sbd), 2)
    return labels_a, labels_b


# --- figures -----------------------------------------------------------------------------

COLS, GAP_X, X_LEFT = 3, 18, 4
CELL_W = (WIDTH - 2 * X_LEFT - (COLS - 1) * GAP_X) / COLS
LABEL_H, PLOT_H, GAP_Y = 16, 50, 16


def multiples(names, rows, top, lo, hi, cls="ln"):
    """Small multiples, three per row, each with its name and a baseline at 0 kW. Returns (body, bottom)."""
    pitch = LABEL_H + PLOT_H + GAP_Y
    body = []
    for k, (name, y) in enumerate(zip(names, rows)):
        r, c = divmod(k, COLS)
        x0 = X_LEFT + c * (CELL_W + GAP_X)
        y0 = top + r * pitch
        body.append(text(x0, y0 + 12, name))
        base = y0 + LABEL_H + PLOT_H
        body.append(line(x0, base, x0 + CELL_W, base))
        body.append(polyline(series_points(y, x0, CELL_W, y0 + LABEL_H, PLOT_H, lo, hi), cls, ' stroke-width="1.5"'))
    n_rows = (len(names) + COLS - 1) // COLS
    return body, top + (n_rows - 1) * pitch + LABEL_H + PLOT_H


def day_hints(bottom):
    """00:00 and 24:00 under the first cell of the last row: one short time axis for the whole figure."""
    return [text(X_LEFT, bottom + 16, "00:00"), text(X_LEFT + CELL_W, bottom + 16, "24:00", "t-sm t-mono end")]


def fig_demand12(ids, X, lo, hi):
    """Small multiples: the 12 days in fixture order, three per row, one shared scale, all in ink."""
    body, bottom = multiples(ids, X, 0, lo, hi)
    body.extend(day_hints(bottom))
    title = "Twelve days of electricity demand"
    desc = (f"Small multiples of the {len(ids)} fixture days ({', '.join(ids)}), 48 half-hour samples "
            f"from 00:00 to 24:00 each, drawn on one shared scale from {lo:g} to {hi:g} kW.")
    return document(bottom + 22, title, desc, body)


def fig_groups(ids, X, labels, lo, hi, title, desc_head):
    """One panel per recovered group, stacked: the group's days as small multiples on the shared scale.

    Labels are 0-based in order of first appearance, so group 1 holds mon: it is drawn in ink
    (series A), group 2 in accent (series B).
    """
    classes = {0: "ln", 1: "ln-accent"}
    head_h, gap = 26, 30
    body, parts = [], []
    top = 0
    for g in sorted(set(labels)):
        members = [k for k, lab in enumerate(labels) if lab == g]
        body.append(text(X_LEFT, top + 15, f"Group {g + 1}", "t"))
        cells, bottom = multiples([ids[k] for k in members], X[members], top + head_h, lo, hi, classes[g])
        body.extend(cells)
        parts.append(f"group {g + 1}: " + ", ".join(ids[k] for k in members))
        top = bottom + gap
    bottom = top - gap
    body.extend(day_hints(bottom))
    desc = (f"{desc_head} Two panels, one per group, each day drawn on its own on one shared scale: "
            + ". ".join(parts) + ".")
    return document(bottom + 22, title, desc, body)


def fig_lockstep_vs_dtw(x, y, euclid, dtw4):
    """mon (ink) above sat (accent), linked sample by sample, then along the DTW path (w = 4)."""
    x_lab, x0 = 4, 40
    w = WIDTH - x0 - 4
    head_h, band_h, mid_gap, gap = 22, 44, 30, 30
    lo = float(min(x.min(), y.min()))
    hi = float(max(x.max(), y.max()))
    panels = [("Lock-step", f"Euclidean {euclid}", [(i, i) for i in range(len(x))]),
              (f"DTW, w = {W_DTW}", f"DTW {dtw4}", dtw_path(x, y, W_DTW))]
    body = []
    top = 0
    for name, value, pairs in panels:
        body.append(text(x_lab, top + 14, name, "t"))
        body.append(text(WIDTH - 4, top + 14, value, "t-sm t-mono end"))
        top_a = top + head_h
        top_b = top_a + band_h + mid_gap
        pa = series_points(x, x0, w, top_a, band_h, lo, hi)
        pb = series_points(y, x0, w, top_b, band_h, lo, hi)
        # every second link, so each one stays visible at 375 px; the last one is always drawn
        keep = [k for k in range(len(pairs)) if k % 2 == 0 or k == len(pairs) - 1]
        for k in keep:
            i, j = pairs[k]
            body.append(line(pa[i][0], pa[i][1], pb[j][0], pb[j][1]))
        body.append(polyline(pa, "ln"))
        body.append(polyline(pb, "ln-accent"))
        body.append(text(x_lab, top_a + band_h - 4, "mon"))
        body.append(text(x_lab, top_b + band_h - 4, "sat"))
        top = top_b + band_h + gap
    bottom = top - gap
    body.extend(hour_hints(x0, w, bottom + 18))
    height = bottom + 24
    title = "Lock-step links against DTW links for mon and sat"
    desc = (f"Two panels. Top: mon (ink) and sat (accent) linked sample i to sample i, Euclidean distance {euclid}. "
            f"Bottom: the same days linked along the DTW warping path with window w = {W_DTW}, DTW distance {dtw4}. "
            "The DTW links lean to match each peak of mon with the later peak of sat. Every second link is drawn.")
    return document(height, title, desc, body)


def fig_dtw_window(x, y):
    """Cost grid of mon (rows i, upward) against sat (columns j), the band |i - j| <= w, the path."""
    n = len(x)
    strip, gap, g0y = 44, 8, 24  # g0y leaves room for the mon label above the left strip
    g0x = 4 + strip + gap
    size = WIDTH - 4 - g0x
    cell = size / n
    lo = float(min(x.min(), y.min()))
    hi = float(max(x.max(), y.max()))
    cost = (x[:, None] - y[None, :]) ** 2
    cmax = float(max(cost[i, j] for i in range(n) for j in range(n) if abs(i - j) <= W_DTW))
    body = []

    def cx(j):
        return g0x + (j + 0.5) * cell

    def cy(i):  # row i counted from the bottom
        return g0y + size - (i + 0.5) * cell

    # band cells only: outside the window DTW never computes a cost
    for i in range(n):
        for j in range(max(0, i - W_DTW), min(n, i + W_DTW + 1)):
            op = 0.12 + 0.78 * np.sqrt(cost[i, j] / cmax)
            body.append(f'<rect class="fill-muted" x="{f(g0x + j * cell)}" y="{f(g0y + size - (i + 1) * cell)}" '
                        f'width="{f(cell)}" height="{f(cell)}" opacity="{op:.2f}"/>')
    body.append(f'<rect class="ln-soft" x="{f(g0x)}" y="{f(g0y)}" width="{f(size)}" height="{f(size)}"/>')
    body.append(line(g0x, g0y + size, g0x + size, g0y, "ln-soft", ' stroke-dasharray="3 4"'))
    path = dtw_path(x, y, W_DTW)
    body.append(polyline([(cx(j), cy(i)) for i, j in path], "ln"))
    # the band label sits in the empty upper-left corner, outside the window
    body.append(text(g0x + 10, g0y + 22, f"|i − j| ≤ {W_DTW}", "t-sm t-mono"))
    body.append(text(g0x + 10, g0y + 40, "the window", "t-sm"))
    # mon along the left edge: time runs upward, demand points left (the usual plot turned a quarter turn)
    left = [(4 + strip - strip * (v - lo) / (hi - lo), g0y + size - size * (i * 0.5) / 24.0) for i, v in enumerate(x)]
    body.append(polyline(left, "ln", ' stroke-width="1.5"'))
    body.append(text(4, g0y - 10, "mon"))
    # sat under the grid
    s_top = g0y + size + gap
    body.append(polyline(series_points(y, g0x, size, s_top, strip, lo, hi), "ln-accent", ' stroke-width="1.5"'))
    body.append(text(4, s_top + strip - 2, "sat"))
    body.extend(hour_hints(g0x, size, s_top + strip + 18))
    height = s_top + strip + 24
    off = max(abs(i - j) for i, j in path)
    title = f"The DTW cost grid of mon and sat with the window w = {W_DTW}"
    desc = (f"A {n} by {n} grid: rows are the samples i of mon (drawn along the left edge, time upward), columns the "
            f"samples j of sat (drawn below). Only the band |i \u2212 j| \u2264 {W_DTW} is shaded, darker where the squared "
            f"difference is larger. The dashed diagonal is lock-step matching. The warping path runs from the bottom-left "
            f"corner to the top-right corner inside the band, at most {off} samples off the diagonal.")
    return document(height, title, desc, body)


def fig_dtw_matrix(ids, D, labels):
    """12 x 12 DTW (w = 4) matrix ordered by group: darker means closer, one class, opacity only."""
    order = sorted(range(len(ids)), key=lambda k: (labels[k], k))
    n = len(order)
    lab_w, lab_h, block_gap, pitch, gap = 36, 22, 6, 26, 2
    x0, y0 = lab_w + 4, lab_h
    dmax = float(D.max())

    def pos(r):  # position of row or column r, with a gap between the two groups
        first_of_second = sum(1 for k in order if labels[k] == labels[order[0]])
        return r * pitch + (block_gap if r >= first_of_second else 0)

    def opacity(d):
        return 0.06 + 0.94 * (1 - d / dmax)

    body = []
    for c, k in enumerate(order):
        body.append(text(x0 + pos(c) + (pitch - gap) / 2, y0 - 8, ids[k], "t-sm t-mono mid"))
    for r, a in enumerate(order):
        body.append(text(x0 - 6, y0 + pos(r) + (pitch - gap) / 2 + 4, ids[a], "t-sm t-mono end"))
        for c, b in enumerate(order):
            body.append(f'<rect class="fill-ink" x="{f(x0 + pos(c))}" y="{f(y0 + pos(r))}" width="{f(pitch - gap)}" '
                        f'height="{f(pitch - gap)}" rx="2" opacity="{opacity(D[a, b]):.2f}"/>')
    grid_bottom = y0 + pos(n - 1) + pitch - gap
    # legend: five steps from distance 0 to the largest distance in the matrix
    ly = grid_bottom + 22
    steps = 5
    sw = 22
    lx = x0
    body.append(text(lx, ly + 12, "0"))
    for s in range(steps):
        d = dmax * s / (steps - 1)
        body.append(f'<rect class="fill-ink" x="{f(lx + 16 + s * (sw + 2))}" y="{f(ly)}" width="{sw}" height="16" '
                    f'rx="2" opacity="{opacity(d):.2f}"/>')
    end = lx + 16 + steps * (sw + 2) + 4
    body.append(text(end, ly + 12, f"{dmax:.2f}"))
    body.append(text(WIDTH - 4, ly + 12, f"DTW, w = {W_DTW}", "t-sm t-mono end"))
    height = ly + 20
    g1 = ", ".join(ids[k] for k in order if labels[k] == labels[order[0]])
    g2 = ", ".join(ids[k] for k in order if labels[k] != labels[order[0]])
    title = f"The 12 by 12 DTW distance matrix (w = {W_DTW}), ordered by group"
    desc = (f"Rows and columns in the same order, group 1 ({g1}) then group 2 ({g2}), from average linkage with k = 2 "
            f"on this matrix. Darker cells are closer pairs, from 0 on the diagonal to {dmax:.2f} for the farthest pair.")
    return document(height, title, desc, body)


# --- main --------------------------------------------------------------------------------

def main():
    ids, X, lo, hi = load()
    mon, sat = X[ids.index("mon")], X[ids.index("sat")]

    euclid = euclidean(mon, sat)
    dtw4 = dtw(mon, sat, W_DTW)
    D = distance_matrix(X, lambda a, b: dtw(a, b, W_DTW))
    labels = average_linkage(D, 2)
    problems = check_dissimilarity(D, labels)
    if problems:
        raise SystemExit("DTW matrix: " + "; ".join(problems))
    numbers = {
        "euclid_mon_sat": f"{euclid:.2f}",
        "dtw4_mon_sat": f"{dtw4:.2f}",
        "ratio_mon_sat": f"{dtw4 / euclid:.2f}",  # DTW over Euclidean, from the unrounded values
        "silhouette_dtw4_k2": f"{silhouette_from_matrix(D, labels):.2f}",
    }
    labels_a, labels_b = question_labels(X)

    figures = {
        "demand-12": fig_demand12(ids, X, lo, hi),
        "question-a": fig_groups(
            ids, X, labels_a, lo, hi, "Question A: days grouped by raw Euclidean distance",
            "Average linkage with k = 2 on raw Euclidean distances between the 12 days."),
        "question-b": fig_groups(
            ids, X, labels_b, lo, hi, "Question B: days grouped by shape (z-normalisation plus SBD)",
            "Average linkage with k = 2 on SBD distances between the z-normalised days."),
        "lockstep-vs-dtw": fig_lockstep_vs_dtw(mon, sat, numbers["euclid_mon_sat"], numbers["dtw4_mon_sat"]),
        "dtw-window": fig_dtw_window(mon, sat),
        "dtw-matrix": fig_dtw_matrix(ids, D, labels),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in figures.items():
        (OUT / f"{name}.svg").write_text(svg)
    (OUT / "numbers.json").write_text(json.dumps(numbers, indent=2, sort_keys=True) + "\n")
    print(f"wrote {len(figures)} figures and numbers.json to {OUT.relative_to(ROOT)}: "
          + ", ".join(f"{k} {v}" for k, v in sorted(numbers.items())))


if __name__ == "__main__":
    main()
