def live_json(data):
    """One key per line, each series on one line: readable diffs, stable bytes."""
    return "{\n" + ",\n".join(f"{json.dumps(k)}: {json.dumps(v)}" for k, v in data.items()) + "\n}\n"


def write_live_svg(live_path):
    data = json.loads(live_path.read_text())
    svg = fig_dtw_explorer(data, data["initial"]["pair"], data["w"]["initial"])
    out = live_path.with_name(live_path.name[:-len(".live.json")] + ".svg")
    out.write_text(svg)
    return out


def main():
    ap = argparse.ArgumentParser()
