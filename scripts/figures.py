def load():
    ids, X, _ = load_demand()
    lo, hi = 0.0, float(np.ceil(X.max() * 10) / 10)  # one shared scale from 0 kW
    return ids, X, lo, hi


def question_labels(X):
    """Question A: raw Euclidean. Question B: z-normalisation plus SBD. Both average linkage, k = 2."""
    labels_a = average_linkage(distance_matrix(X, euclidean), 2)
    Z = np.array([znorm(x) for x in X])
    labels_b = average_linkage(distance_matrix(Z, sbd), 2)
    return labels_a, labels_b


# --- figures -----------------------------------------------------------------------------

COLS, GAP_X, X_LEFT = 3, 18, 4
CELL_W = (WIDTH - 2 * X_LEFT - (COLS - 1) * GAP_X) / COLS
LABEL_H, PLOT_H, GAP_Y = 18, 50, 16


def multiples(names, rows, top, lo, hi, cls="ln"):
    """Small multiples, three per row, each with its name and a baseline at 0 kW. Returns (body, bottom)."""
    pitch = LABEL_H + PLOT_H + GAP_Y
    body = []
    for k, (name, y) in enumerate(zip(names, rows)):
        r, c = divmod(k, COLS)
        x0 = X_LEFT + c * (CELL_W + GAP_X)
        y0 = top + r * pitch
        body.append(text(x0, y0 + 14, name))
        base = y0 + LABEL_H + PLOT_H
        body.append(line(x0, base, x0 + CELL_W, base))
        body.append(polyline(series_points(y, x0, CELL_W, y0 + LABEL_H, PLOT_H, lo, hi), cls, ' stroke-width="1.5"'))
    n_rows = (len(names) + COLS - 1) // COLS
    return body, top + (n_rows - 1) * pitch + LABEL_H + PLOT_H


def day_hints(bottom):
    """00:00 and 24:00 under the first cell of the last row: one short time axis for the whole figure."""
    return [text(X_LEFT, bottom + 16, "00:00"), text(X_LEFT + CELL_W, bottom + 16, "24:00", "t-sm t-mono end")]


def fig_demand12(ids, X, lo, hi):
    """Small multiples: the 12 days in fixture order, three per row, one shared scale, all in ink."""
    body, bottom = multiples(ids, X, 0, lo, hi)
    body.extend(day_hints(bottom))
    title = "Twelve days of electricity demand"
    desc = (f"Small multiples of the {len(ids)} fixture days ({', '.join(ids)}), 48 half-hour samples "
            f"from 00:00 to 24:00 each, drawn on one shared scale from {lo:g} to {hi:g} kW.")
    return document(bottom + 22, title, desc, body)


def fig_groups(ids, X, labels, lo, hi, title, desc_head):
    """One panel per recovered group, stacked: the group's days as small multiples on the shared scale.

    Labels are 0-based in order of first appearance, so group 1 holds mon: it is drawn in ink
    (series A), group 2 in accent (series B).
    """
    classes = {0: "ln", 1: "ln-accent"}
    head_h, gap = 26, 30
    body, parts = [], []
    top = 0
    for g in sorted(set(labels)):
        members = [k for k, lab in enumerate(labels) if lab == g]
        body.append(text(X_LEFT, top + 15, f"Group {g + 1}", "t"))
        cells, bottom = multiples([ids[k] for k in members], X[members], top + head_h, lo, hi, classes[g])
        body.extend(cells)
        parts.append(f"group {g + 1}: " + ", ".join(ids[k] for k in members))
        top = bottom + gap
    bottom = top - gap
    body.extend(day_hints(bottom))
    desc = (f"{desc_head} Two panels, one per group, each day drawn on its own on one shared scale: "
            + ". ".join(parts) + ".")
    return document(bottom + 22, title, desc, body)


def fig_lockstep_vs_dtw(x, y, euclid, dtw4):
    """mon (ink) above sat (accent), linked sample by sample, then along the DTW path (w = 4)."""
    x_lab, x0 = 4, 40
    w = WIDTH - x0 - 4
    head_h, band_h, mid_gap, gap = 22, 44, 30, 30
    lo = float(min(x.min(), y.min()))
    hi = float(max(x.max(), y.max()))
    panels = [("Lock-step", f"Euclidean {euclid}", [(i, i) for i in range(len(x))]),
              (f"DTW, w = {W_DTW}", f"DTW {dtw4}", dtw_path(x, y, W_DTW))]
    body = []
    top = 0
    for name, value, pairs in panels:
        body.append(text(x_lab, top + 14, name, "t"))
        body.append(text(WIDTH - 4, top + 14, value, "t-sm t-mono end"))
        top_a = top + head_h
        top_b = top_a + band_h + mid_gap
        pa = series_points(x, x0, w, top_a, band_h, lo, hi)
        pb = series_points(y, x0, w, top_b, band_h, lo, hi)
        # every second link, so each one stays visible at 375 px; the last one is always drawn
        keep = [k for k in range(len(pairs)) if k % 2 == 0 or k == len(pairs) - 1]
        for k in keep:
            i, j = pairs[k]
            body.append(line(pa[i][0], pa[i][1], pb[j][0], pb[j][1], "ln-muted"))
        body.append(polyline(pa, "ln"))
        body.append(polyline(pb, "ln-accent"))
        body.append(text(x_lab, top_a + band_h - 4, "mon"))
        body.append(text(x_lab, top_b + band_h - 4, "sat"))
        top = top_b + band_h + gap
    bottom = top - gap
    body.extend(hour_hints(x0, w, bottom + 18))
    height = bottom + 24
    title = "Lock-step links against DTW links for mon and sat"
    desc = (f"Two panels. Top: mon (ink) and sat (accent) linked sample i to sample i, Euclidean distance {euclid}. "
            f"Bottom: the same days linked along the DTW warping path with window w = {W_DTW}, DTW distance {dtw4}. "
            "The DTW links lean to match each peak of mon with the later peak of sat. Every second link is drawn.")
    return document(height, title, desc, body)


def fig_dtw_window(x, y):
    """Cost grid of mon (rows i, upward) against sat (columns j), the band |i - j| <= w, the path.

    The side traces put sample i of mon at the centre of row i and sample j of sat at the centre
    of column j, like the path, and their labels give the index direction (mon, i up; sat, j right).
    """
    n = len(x)
    strip, label_w, gap, g0y = 44, 68, 6, 26  # label_w: room for "sat, j →" left of the sat trace
    g0x = 4 + label_w + gap
    size = WIDTH - 4 - g0x
    cell = size / n
    lo = float(min(x.min(), y.min()))
    hi = float(max(x.max(), y.max()))
    cost = (x[:, None] - y[None, :]) ** 2
    cmax = float(max(cost[i, j] for i in range(n) for j in range(n) if abs(i - j) <= W_DTW))
    body = []

    def cx(j):  # centre of column j
        return g0x + (j + 0.5) * cell

    def cy(i):  # centre of row i, rows counted from the bottom
        return g0y + size - (i + 0.5) * cell

    def opacity(c):  # square-root transfer, so small local costs stay visible
        return 0.12 + 0.78 * np.sqrt(c / cmax)

    # band cells only: outside the window DTW never computes a cost
    for i in range(n):
        for j in range(max(0, i - W_DTW), min(n, i + W_DTW + 1)):
            op = opacity(cost[i, j])
            body.append(f'<rect class="fill-muted" x="{f(g0x + j * cell)}" y="{f(g0y + size - (i + 1) * cell)}" '
                        f'width="{f(cell)}" height="{f(cell)}" opacity="{op:.2f}"/>')
    body.append(f'<rect class="ln-soft" x="{f(g0x)}" y="{f(g0y)}" width="{f(size)}" height="{f(size)}"/>')
    body.append(line(g0x, g0y + size, g0x + size, g0y, "ln-soft", ' stroke-dasharray="3 4"'))
    path = dtw_path(x, y, W_DTW)
    body.append(polyline([(cx(j), cy(i)) for i, j in path], "ln"))
    # the band label sits in the empty upper-left corner, outside the window
    body.append(text(g0x + 10, g0y + 22, f"|i − j| ≤ {W_DTW}", "t-sm t-mono"))
    body.append(text(g0x + 10, g0y + 40, "the window", "t-sm"))
    # mon along the left edge, next to the grid: sample i at the height of row i, demand points left
    right = g0x - gap
    left = [(right - strip * (v - lo) / (hi - lo), cy(i)) for i, v in enumerate(x)]
    body.append(polyline(left, "ln", ' stroke-width="1.5"'))
    body.append(text(4, g0y - 10, "mon, i ↑"))
    # sat under the grid: sample j under column j
    s_top = g0y + size + gap
    below = [(cx(j), s_top + strip - strip * (v - lo) / (hi - lo)) for j, v in enumerate(y)]
    body.append(polyline(below, "ln-accent", ' stroke-width="1.5"'))
    body.append(text(4, s_top + strip - 2, "sat, j →"))
    # time ticks on the samples: j = 0 is 00:00, j = 24 is 12:00, j = n - 1 is the last half hour
    t_y = s_top + strip
    last = f"{(n - 1) // 2:02d}:{30 * ((n - 1) % 2):02d}"
    for j, label, anchor in ((0, "00:00", ""), (n // 2, "12:00", " mid"), (n - 1, last, " end")):
        body.append(line(cx(j), t_y + 2, cx(j), t_y + 6))
        body.append(text(cx(j) + (3 if anchor == " end" else -3 if anchor == "" else 0), t_y + 20, label, "t-sm t-mono" + anchor))
    # key: five steps evenly spaced in local cost, so the square-root shading shows in the swatches
    ly = t_y + 34
    steps, sw = 5, 22
    body.append(text(4, ly + 12, "0"))
    for s in range(steps):
        body.append(f'<rect class="fill-muted" x="{f(4 + 14 + s * (sw + 2))}" y="{f(ly)}" width="{sw}" height="16" '
                    f'opacity="{opacity(cmax * s / (steps - 1)):.2f}"/>')
    body.append(text(4 + 14 + steps * (sw + 2) + 4, ly + 12, f"{cmax:.2f}"))
    body.append(text(WIDTH - 4, ly + 12, "local cost", "t-sm end"))
    body.append(text(4, ly + 36, "(mon \u2212 sat)\u00b2 per cell, square-root shading", "t-sm"))
    height = ly + 42
    off = max(abs(i - j) for i, j in path)
    title = f"The DTW cost grid of mon and sat with the window w = {W_DTW}"
    desc = (f"A {n} by {n} grid: rows are the samples i of mon (drawn along the left edge, labelled mon, i up, time "
            f"upward), columns the samples j of sat (drawn below, labelled sat, j right). Each sample of a trace sits "
            f"at the centre of its row or column, with time ticks at 00:00, 12:00 and {last}. Only the band "
            f"|i \u2212 j| \u2264 {W_DTW} is drawn. Higher opacity means "
            f"higher local cost, the squared difference of the two samples (not the accumulated cost), from 0 to "
            f"{cmax:.2f} in the band, with opacity growing as its square root. The dashed diagonal is lock-step matching. The warping path runs from the bottom-left "
            f"corner to the top-right corner inside the band, at most {off} samples off the diagonal.")
    return document(height, title, desc, body)


def fig_dtw_explorer(data, pair, w):
    """The live DTW figure in one state: top panel of two series with links, then the cost grid.

    Static twin of what site/live.js redraws, so it follows the same geometry contract (AGENTS.md):
    series A above series B on one shared value scale, links along the DTW path for even path steps and
    the last one, the band cells of |i - j| <= w (every cell with w None), the path through the cell
    centres. data-part marks the parts and the root carries data-pair and data-w.
    """
    na, nb = data["pairs"][pair]
    a = np.array(data["series"][na], dtype=float)
    b = np.array(data["series"][nb], dtype=float)
    n = len(a)
    ww = n if w is None else w  # an effective window that never binds
    euclid, dist = euclidean(a, b), dtw(a, b, w)
    path = dtw_path(a, b, w)
    lo, hi = float(min(a.min(), b.min())), float(max(a.max(), b.max()))
    if hi == lo:
        hi = lo + 1.0
    x_lab, x0 = 4, 40
    wt = WIDTH - x0 - 4
    head_h, band_h, mid_gap, gap = 22, 44, 30, 30
    top_a = head_h
    top_b = top_a + band_h + mid_gap
    body = [text(x_lab, 14, f"Euclidean {euclid:.2f}", "t-sm t-mono"), text(WIDTH - 4, 14, f"DTW {dist:.2f}", "t-sm t-mono end")]

    def tx(i):
        return x0 + (wt * i / (n - 1) if n > 1 else 0)

    def ty(v, top):
        return top + band_h - band_h * (v - lo) / (hi - lo)

    pa = [(tx(i), ty(v, top_a)) for i, v in enumerate(a)]
    pb = [(tx(j), ty(v, top_b)) for j, v in enumerate(b)]
    for k in range(len(path)):
        if k % 2 == 0 or k == len(path) - 1:
            i, j = path[k]
            body.append(line(pa[i][0], pa[i][1], pb[j][0], pb[j][1], "ln-muted", ' data-part="link"'))
    body.append(polyline(pa, "ln", ' data-part="series-a"'))
    body.append(polyline(pb, "ln-accent", ' data-part="series-b"'))
    body.append(text(x_lab, top_a + band_h - 4, na))
    body.append(text(x_lab, top_b + band_h - 4, nb))
    # grid
    strip, label_w, gx_gap = 44, 68, 6
    g0x = 4 + label_w + gx_gap
    size = WIDTH - 4 - g0x
    g0y = top_b + band_h + gap + 26
    cell = size / n
    cost = (a[:, None] - b[None, :]) ** 2
    band = [(i, j) for i in range(n) for j in range(n) if abs(i - j) <= ww]
    cmax = float(max(cost[i, j] for i, j in band))

    def opacity(c):
        return 0.12 + 0.78 * (np.sqrt(c / cmax) if cmax > 0 else 0.0)

    def cx(j):
        return g0x + (j + 0.5) * cell

    def cy(i):
        return g0y + size - (i + 0.5) * cell

    for i, j in band:
        body.append(f'<rect class="fill-muted" data-part="cell" x="{f(g0x + j * cell)}" y="{f(g0y + size - (i + 1) * cell)}" '
                    f'width="{f(cell)}" height="{f(cell)}" opacity="{opacity(cost[i, j]):.2f}"/>')
    body.append(f'<rect class="ln-soft" data-part="grid" x="{f(g0x)}" y="{f(g0y)}" width="{f(size)}" height="{f(size)}"/>')
    body.append(line(g0x, g0y + size, g0x + size, g0y, "ln-soft", ' stroke-dasharray="3 4"'))
    body.append(polyline([(cx(j), cy(i)) for i, j in path], "ln", ' data-part="path"'))
    body.append(text(g0x + 10, g0y + 22, "no window" if w is None else f"|i \u2212 j| \u2264 {w}", "t-sm t-mono"))
    right = g0x - gx_gap
    body.append(polyline([(right - strip * (v - lo) / (hi - lo), cy(i)) for i, v in enumerate(a)], "ln", ' stroke-width="1.5"'))
    body.append(text(4, g0y - 10, f"{na}, i \u2191"))
    s_top = g0y + size + gx_gap
    body.append(polyline([(cx(j), s_top + strip - strip * (v - lo) / (hi - lo)) for j, v in enumerate(b)], "ln-accent",
                         ' stroke-width="1.5"'))
    body.append(text(4, s_top + strip - 2, f"{nb}, j \u2192"))
    ly = s_top + strip + 14
    steps, sw = 5, 22
    body.append(text(4, ly + 12, "0"))
    for s in range(steps):
        body.append(f'<rect class="fill-muted" x="{f(4 + 14 + s * (sw + 2))}" y="{f(ly)}" width="{sw}" height="16" '
                    f'opacity="{opacity(cmax * s / (steps - 1)):.2f}"/>')
    body.append(text(4 + 14 + steps * (sw + 2) + 4, ly + 12, f"{cmax:.2f}"))
    body.append(text(WIDTH - 4, ly + 12, "local cost", "t-sm end"))
    height = ly + 24
    wtxt = "no window" if w is None else f"window w = {w}"
    title = f"DTW of {na} and {nb} with {wtxt}"
    desc = (f"Pair {na} and {nb}, {wtxt}. Euclidean distance {euclid:.2f}, DTW distance {dist:.2f}. Top: {na} (ink) above "
            f"{nb} (accent) on one scale, linked along the DTW warping path (every second link is drawn). Bottom: a {n} by "
            f"{n} grid, rows the samples of {na} from the bottom, columns the samples of {nb} from the left. Only the band "
            f"of allowed cells is drawn. Higher opacity means higher local cost, the squared difference of the two samples, "
            f"from 0 to {cmax:.2f}. The dashed diagonal is lock-step matching and the line through the cells is the warping path.")
    svg = document(height, title, desc, body)
    return svg.replace("<svg ", f'<svg data-pair="{na}-{nb}" data-w="{"none" if w is None else w}" ', 1)


def fig_dtw_matrix(ids, D, labels):
    """12 x 12 DTW (w = 4) matrix ordered by group: higher opacity means closer, one class, opacity only."""
    order = sorted(range(len(ids)), key=lambda k: (labels[k], k))
    n = len(order)
    lab_w, lab_h, block_gap, pitch, gap = 36, 38, 6, 26, 2  # lab_h: two rows of column labels
    x0, y0 = lab_w + 4, lab_h
    dmax = float(D.max())

    def pos(r):  # position of row or column r, with a gap between the two groups
        first_of_second = sum(1 for k in order if labels[k] == labels[order[0]])
        return r * pitch + (block_gap if r >= first_of_second else 0)

    def opacity(d):
        return 0.06 + 0.94 * (1 - d / dmax)

    body = []
    # column labels alternate between two rows: at 14 units a three-letter name is wider than a cell
    for c, k in enumerate(order):
        body.append(text(x0 + pos(c) + (pitch - gap) / 2, y0 - (8 if c % 2 == 0 else 24), ids[k], "t-sm t-mono mid"))
    for r, a in enumerate(order):
        body.append(text(x0 - 6, y0 + pos(r) + (pitch - gap) / 2 + 4, ids[a], "t-sm t-mono end"))
        for c, b in enumerate(order):
            body.append(f'<rect class="fill-ink" x="{f(x0 + pos(c))}" y="{f(y0 + pos(r))}" width="{f(pitch - gap)}" '
                        f'height="{f(pitch - gap)}" rx="2" opacity="{opacity(D[a, b]):.2f}"/>')
    grid_bottom = y0 + pos(n - 1) + pitch - gap
    # legend: five steps from distance 0 to the largest distance in the matrix
    ly = grid_bottom + 22
    steps = 5
    sw = 22
    lx = x0
    body.append(text(lx, ly + 12, "0"))
    for s in range(steps):
        d = dmax * s / (steps - 1)
        body.append(f'<rect class="fill-ink" x="{f(lx + 16 + s * (sw + 2))}" y="{f(ly)}" width="{sw}" height="16" '
                    f'rx="2" opacity="{opacity(d):.2f}"/>')
    end = lx + 16 + steps * (sw + 2) + 4
    body.append(text(end, ly + 12, f"{dmax:.2f}"))
    body.append(text(WIDTH - 4, ly + 12, f"DTW, w = {W_DTW}", "t-sm t-mono end"))
    height = ly + 20
    g1 = ", ".join(ids[k] for k in order if labels[k] == labels[order[0]])
    g2 = ", ".join(ids[k] for k in order if labels[k] != labels[order[0]])
    title = f"The 12 by 12 DTW distance matrix (w = {W_DTW}), ordered by group"
    desc = (f"Rows and columns in the same order, group 1 ({g1}) then group 2 ({g2}), from average linkage with k = 2 "
            f"on this matrix. Higher opacity means a smaller distance: full opacity for 0 on the diagonal, lowest "
            f"opacity for {dmax:.2f}, the farthest pair.")
    return document(height, title, desc, body)


