"""Generate the pilot figures (content/figures/*.svg) and numbers (content/figures/numbers.json).

Every drawn or quoted number comes from the tsc package on the frozen fixture
(fixtures/demand-12.csv). The SVG uses only the figure classes of site/theme.css,
so the theme decides every colour. Colours keep one meaning: series A (mon) or the
first group in ink, series B (sat) or the second group in accent, soft links and
frames in the line colour. Output is deterministic: same bytes on every run.

Run: uv run python scripts/figures.py
     uv run python scripts/figures.py --smoke   (only the SVGs of the smoke course's .live.json files)
"""

